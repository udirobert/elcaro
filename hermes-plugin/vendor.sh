#!/usr/bin/env bash
# Vendors the elcaro detection engine subset into elcaro_engine/ for the
# Hermes plugin. core/ stays the source of truth — re-run after core changes:
#     ./vendor.sh
# Rewrites `from core.` imports to package-relative form so the engine loads
# inside the plugin package with no absolute-path assumptions.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$(cd "$(dirname "$0")" && pwd)/elcaro_engine"

rm -rf "$DEST"
mkdir -p "$DEST/detectors"

TOP="schemas.py taxonomy.py autopsy.py normalize.py quarantine.py signing.py canary.py \
llm_classifier.py serv_reasoner.py jev_reasoner.py jev_vl_reasoner.py \
laya_reasoner.py"

for f in $TOP; do
    sed -e 's/^from core\.detectors\./from .detectors./' \
        -e 's/^from core\./from ./' \
        "$ROOT/core/$f" > "$DEST/$f"
done

for f in "$ROOT"/core/detectors/*.py; do
    sed -e 's/^from core\.detectors import/from . import/' \
        -e 's/^from core\./from ../' \
        "$f" > "$DEST/detectors/$(basename "$f")"
done

cat > "$DEST/__init__.py" <<'EOF'
"""Vendored elcaro detection engine for the Hermes plugin.

GENERATED by vendor.sh — do not edit; edit core/ and re-vendor instead.
Exposes exactly what the plugin's guard and tools layers need.
"""

from .quarantine import DEFAULT_RISK_THRESHOLD
from .schemas import (
    ContentType,
    DetectionIndicator,
    RiskLevel,
    ScanRequest,
    ScanResponse,
    TechniqueClass,
)
from .signing import (
    VerdictSigner,
    canonical_verdict_payload,
    sha256_hex,
    verify_verdict,
)
from .taxonomy import IpiDetectionEngine

__all__ = [
    "IpiDetectionEngine",
    "ScanRequest",
    "ScanResponse",
    "ContentType",
    "RiskLevel",
    "TechniqueClass",
    "DetectionIndicator",
    "VerdictSigner",
    "canonical_verdict_payload",
    "sha256_hex",
    "verify_verdict",
    "DEFAULT_RISK_THRESHOLD",
]
EOF

echo "vendored $(ls "$DEST"/*.py "$DEST"/detectors/*.py | wc -l | tr -d ' ') files into $DEST"
